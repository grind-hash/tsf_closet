# 日本語の文に紛れた簡体字を見つける(置き換え表の字)
SIMPLIFIED_ONLY_CHARS = frozenset(
    chr(code)
    for code in _SIMPLIFIED_TO_JAPANESE
    if chr(code) != _SIMPLIFIED_TO_JAPANESE[code]
)


def normalize_japanese(text: str) -> str:
    """日本語の生成文に混ざった簡体字を、日本の漢字へ置き換える。"""
    return str(text or "").translate(_SIMPLIFIED_TO_JAPANESE)


def normalize_output(text: str, language: str) -> str:
    return normalize_japanese(text) if language == "ja" else str(text or "")
